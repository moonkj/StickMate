namespace StickMate.Core
{
    /// <summary>
    /// ★★★ <b>캐릭터가 안 보이는 동안에는 「캐릭터가 하는 일」을 시킬 수 없다</b> — 2026-09-03.
    ///
    /// ============================================================================
    /// 무엇을 고치는가 (실측)
    /// ============================================================================
    /// 같은 날 사용자 명시 숨김이 <b>캐릭터만</b> 가리도록 좁아지면서
    /// (<see cref="StickmanAgent.HidesScreenSurfaces"/>) 톱니·부채꼴·행동 명령창이 <b>남게</b> 됐다.
    /// 그 자체는 사용자 확정이지만(<i>"메뉴버튼은 보여야지"</i>), 부작용이 하나 딸려 왔다 —
    /// <b>보이지 않는 캐릭터에게 연출을 시키는 마우스 경로가 열렸다.</b>
    ///
    /// <para>배치모드 실측(<c>coder</c> 프로브, 2026-09-03): 숨김 상태에서
    /// <c>GraffitiDirector.ForceTriggerNow</c>가 <c>started=True</c>로 <b>실제 발동</b>했고 상태가
    /// <c>Graffiti</c>로 전이했다. 가출도 같았다(<c>Runaway</c>). 활쏘기·말걸기의 실패는 숨김 때문이
    /// 아니라 각각 «과녁 자리 없음»·«상태 게이트»였다 — 즉 <b>어느 경로에도 숨김 가드가 없었다</b>.</para>
    ///
    /// ============================================================================
    /// 왜 이 문제인가 — 절대 불변 원칙 1
    /// ============================================================================
    /// 대사는 <b>상태 전이가 확정된 뒤 그 상태에서만</b> 파생된다. 보이지 않는 캐릭터가 그라피티를
    /// 그리면 상태와 화면이 갈라지고, 그 상태에서 파생된 말풍선이 <b>주인 없이</b> 뜬다.
    ///
    /// ============================================================================
    /// 어느 값으로 거는가 — <b><see cref="StickmanAgent.IsSuspended"/>다</b>
    /// ============================================================================
    /// 조건은 <b>「캐릭터가 안 보인다」</b>이지 「표면을 걷는다」가 아니다.
    /// <see cref="StickmanAgent.HidesScreenSurfaces"/>로 걸면 <b>사용자 명시 숨김에서 안 막힌다</b> —
    /// 그게 정확히 이 파일이 고치려는 결함이다. <b>바꾸지 마라.</b>
    ///
    /// ============================================================================
    /// 무엇을 막지 <b>않는가</b> (막으면 또 갇힌다)
    /// ============================================================================
    /// 이 게이트는 <b>캐릭터가 보여야 성립하는 명령</b>에만 붙는다. 아래는 절대 대상이 아니다:
    /// <list type="bullet">
    ///   <item><b>숨김 해제</b>(<c>ControlAction.UserHide</c>) — 막는 순간 사용자가 갇힌다.
    ///     2026-09-03 신고 그 자체다.</item>
    ///   <item><b>설정창 / 정보창 열기</b> — 되돌리는 버튼이 그 안에 있다.</item>
    ///   <item><b>앱 종료</b> — 마지막 탈출구다.</item>
    ///   <item><b>가출 [돌아와!] 소환</b>(<c>RunawayDirector.GetRecallAvailability</c>) —
    ///     UX_FLOW 20절이 <b>상시</b> 제공을 요구한 탈출구다. 막는 쪽이 <b>발동</b>
    ///     (<c>GetForcedRunawayAvailability</c>)이고, 되돌리는 쪽은 열어 둔다.</item>
    ///   <item><b>잉크색·로데오 토글, 진단 로그</b> — 설정 값 변경이지 캐릭터 연출이 아니다.</item>
    ///   <item><b>스트레스 게이지 순환</b>(개발 전용) — 19절이 <i>"화면에는 숫자도 막대도 그리지 않는다"</i>고
    ///     못박은 <b>내부 수치</b>다. 그 수치가 임계값을 넘어 발동시키는 연출들은 각자의
    ///     <c>Update</c>가 이미 <c>IsSuspended</c>로 막는다.</item>
    /// </list>
    ///
    /// ============================================================================
    /// 왜 새 창구를 만들지 않았는가
    /// ============================================================================
    /// 리더 지시: <b>기존 <c>IsReady</c>/<c>Reason</c> 창구를 그대로 쓴다.</b> 각 Director의
    /// <c>GetAvailability()</c> 하나가 회색 처리와 실제 실행을 <b>동시에</b> 결정하므로
    /// (<see cref="CommandAvailability"/> 문서의 36-7 절대 규칙), 여기 한 줄을 넣으면
    /// <b>행동 명령창 타일과 전역 단축키가 같은 답</b>을 낸다. 판정을 두 벌로 만들면 반드시 갈라진다.
    /// </summary>
    public static class HiddenCharacterCommandGate
    {
        /// <summary>
        /// ★★ <b>임시 문구 — <c>design-narrative</c> 확정 대기</b>(리더 지시 2026-09-03:
        /// <i>"문구는 네가 짓지 말고 design-narrative 소관으로 남겨라"</i>).
        ///
        /// <para>지금 값은 같은 표의 다른 사유들
        /// (<c>"과녁 놓을 자리가 없어요"</c> / <c>"낙서할 빈 자리가 없어요"</c> /
        /// <c>"지금은 집에 있어요"</c>)과 <b>어조·길이만</b> 맞춘 자리표시자다.
        /// 배선과 자리는 확정이고 <b>글자만</b> 미확정이다.</para>
        ///
        /// <para><b>const가 아니라 여기 한 곳에만 둔다</b>: 테스트는 이 상수를 <b>참조</b>해야 하고
        /// 문자열로 베끼면 안 된다(CLAUDE.md). <c>design-narrative</c>가 글자를 바꾸는 날
        /// 테스트가 조용히 초록으로 남지 않게 하는 것이 이 배치의 목적이다.</para>
        /// </summary>
        public const string HiddenReason = "지금은 숨어 있어요";

        /// <summary>미리 만들어 둔 결과 하나. <see cref="CommandAvailability"/> 문서가 요구하는 계약이다 —
        /// 이 값은 창이 열려 있는 동안 0.25초마다 타일마다 다시 계산되므로 그때마다 문자열을 만들면
        /// 하루 종일 켜져 있는 앱에서 그게 곧 GC다.</summary>
        public static readonly CommandAvailability WhileHidden = CommandAvailability.Blocked(HiddenReason);

        /// <summary>
        /// 지금 이 명령을 막아야 하는가.
        /// <para><paramref name="player"/>가 <c>null</c>이면 <b>false</b>다 — 배선 누락은 이 게이트가
        /// 아니라 호출부의 <see cref="CommandAvailability.Missing"/>이 말해야 한다.
        /// 여기서 true를 돌려주면 «숨어 있어요»가 «배선이 없어요»를 <b>가려 버린다</b>.</para>
        /// </summary>
        public static bool BlocksNow(StickmanAgent player) => player != null && player.IsSuspended;
    }
}
