namespace StickMate.Platform
{
    /// <summary>
    /// ★★ 2026-09-02 — <b>절대 불변 원칙 3의 승인된 예외</b>가 지나가는 유일한 통로.
    ///
    /// 사용자 지시(원문): <i>"일단 우리 프로그램을 실행하면 작업표시줄 숨김처리가 되어 있어도 강제로
    /// 보이게 해야함"</i>. 리더가 원칙 3과의 충돌을 명시하고 선택지 3개를 제시했으며, 사용자가
    /// <b>"실행 중에만 + 종료 시 원복"</b>을 골랐다(2026-09-02 확정).
    ///
    /// ============================================================================
    /// 왜 이것이 원칙 3의 "예외"인가 — 숨기지 않고 정면으로 적는다
    /// ============================================================================
    /// 작업표시줄/Dock도 <b>남의 창</b>이고, 자동 숨김 해제는 <b>시스템 전역 설정 변경</b>이다.
    /// 즉 이 인터페이스는 원칙 3("실제 파일/아이콘/타 윈도우는 절대 이동·삭제·수정하지 않는다")이
    /// 금지하는 방향을 <b>의도적으로</b> 한 칸 연다. 이 저장소의 다른 어떤 코드도 그 방향으로 열려
    /// 있지 않으며, 앞으로도 그래야 한다.
    ///
    /// <para><b>그래서 예외의 범위를 계약 자체로 좁힌다.</b> 이 인터페이스에는 메서드가 둘뿐이고,
    /// 쓰기는 <b>자동 숨김 비트 하나</b>다. 막대를 옮기거나(<c>ABM_SETPOS</c>), 크기를 바꾸거나,
    /// 우리를 도킹 앱바로 등록해 화면을 예약하거나(<c>ABM_NEW</c>/<c>ABM_SETAUTOHIDEBAR</c>),
    /// 다른 프로세스를 재시작하는 능력은 <b>여기에 없고 앞으로도 추가하지 않는다</b>. 그 금지는
    /// 문서가 아니라 <c>Tests/EditMode/UserAssetImmutabilityAuditTests</c>가 기계적으로 지킨다.</para>
    ///
    /// <para>읽기 전용 실측인 <see cref="IReservedBottomBarService"/>와 <b>일부러 분리</b>했다.
    /// 그 인터페이스의 문서는 "이 인터페이스의 구현체는 작업표시줄을 바꾸는 API를 절대 부르지
    /// 않는다"고 못박고 있다 — 그 문장을 참으로 유지하려면 쓰기 능력이 다른 타입, 다른 파일에
    /// 있어야 한다. 읽기 계약이 쓰기 능력을 겸하는 순간 "조회만 한다"는 보증이 사라진다.</para>
    ///
    /// ============================================================================
    /// 계약 — 사실 조회 + 최소 쓰기 하나. 정책은 여기 없다
    /// ============================================================================
    /// "바꿔야 하는가 / 되돌려야 하는가 / 흔적이 남아 있는가"는 <b>한 줄도</b> 이 인터페이스나
    /// 그 구현체가 정하지 않는다. 전부 플랫폼 중립 <see cref="ReservedBarRevealPolicy"/>가 정하고,
    /// 구현체는 OS에 묻고 OS에 쓰기만 한다(CLAUDE.md: 정책은 중립 위치, 플랫폼 코드는 사실 조회).
    /// 이 분리가 없으면 macOS가 같은 규칙을 물리적으로 재사용할 수 없다
    /// (실제 사고: <c>FullscreenSuspendPolicy.cs</c>가 <c>Platform/MacOS/</c> 안에 있었다).
    ///
    /// <para><b>선택적 캐퍼빌리티</b>다 — <see cref="IReservedBottomBarService"/>/
    /// <see cref="ICursorPositionService"/>와 같은 관례. 구현하지 않는 플랫폼(현재 macOS/모바일)에서는
    /// <see cref="ReservedBarRevealDirector"/>가 아무 일도 하지 않고, 디스크에 흔적도 남기지 않는다.
    /// macOS를 이번 라운드에서 구현하지 않은 근거는 <c>docs/TASKBAR_REVEAL.md</c> 3절.</para>
    /// </summary>
    public interface IReservedBarAutoHideControl
    {
        /// <summary>
        /// OS가 지금 보고하는 자동 숨김 상태. <b>추정하지 않는다</b> — 못 읽으면 false를 돌려주고,
        /// 그때 정책은 "아무 것도 하지 않는다"로 간다(모르면 남의 설정을 건드리지 않는다).
        /// </summary>
        /// <param name="autoHideEnabled">true면 지금 자동 숨김이 켜져 있다.</param>
        /// <returns>조회에 성공했는가.</returns>
        bool TryReadAutoHide(out bool autoHideEnabled);

        /// <summary>
        /// 자동 숨김 비트를 그 값으로 만든다. <b>이 앱이 시스템 전역 설정에 쓰는 유일한 지점</b>이다.
        ///
        /// <para>구현체는 쓴 뒤 <b>반드시 되읽어</b> 실제로 반영됐는지 확인해야 한다. 이 계열 API는
        /// "요청을 접수했다"만 알려주고 성공 여부를 알려주지 않는 경우가 있어, 반환값만 믿으면
        /// 실패를 성공으로 로그하게 된다(이 저장소의 <c>UniWinCore.IsTopmost</c> 캐시 사고와 같은
        /// 형태 — <see cref="TopmostRestorePolicy"/> 문서 참고).</para>
        /// </summary>
        /// <param name="autoHideEnabled">만들 값. true = 자동 숨김 켜기(원복 방향), false = 강제로 보이기.</param>
        /// <returns>되읽기까지 마쳐 실제로 그 값이 됐는가.</returns>
        bool TrySetAutoHide(bool autoHideEnabled);

        /// <summary>로그에 찍을 플랫폼 꼬리표("Windows" 등). 흔적 파일에도 함께 남아,
        /// 다른 플랫폼에서 만든 흔적을 실수로 적용하는 것을 막는다.</summary>
        string PlatformTag { get; }
    }
}
