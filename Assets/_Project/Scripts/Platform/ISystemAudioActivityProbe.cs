namespace StickMate.Platform
{
    /// <summary>
    /// ★★★ <b>「지금 시스템에서 소리가 나고 있는가」 — 그 한 비트만 묻는 계약</b> (2026-09-03 신설).
    ///
    /// <para>사용자 확정 2건이 이 계약의 범위를 정했다:
    /// <i>"소리시스템을 전체빼줘, 다만 시스템에서 노래가 나오면 상호 반응해서 춤추는 동작을 넣어줘"</i> /
    /// <i>"노래소리만감지 제목알필요없음"</i>. 즉 <b>곡명도, 장르도, 레벨도 묻지 않는다.</b></para>
    ///
    /// ============================================================================
    /// ★ 왜 <b>불리언</b>인가 — 레벨을 계약에 넣으면 macOS 구현체가 값을 지어내야 한다 (I-13)
    /// ============================================================================
    /// 두 플랫폼의 신호는 <b>같은 종류가 아니다</b>
    /// (<c>docs/GAME_ARCHITECTURE_REVIEW.md</c> §11-3 표):
    /// <code>
    ///                    | macOS                          | Windows
    ///   -----------------+--------------------------------+-----------------------------
    ///   원천 API         | kAudioDevicePropertyDevice     | IAudioMeterInformation
    ///                    |   IsRunningSomewhere           |   ::GetPeakValue
    ///   신호 형태        | 불리언 (0/1)                    | 연속 레벨 (0.0~1.0)
    ///   답하는 질문      | "출력 스트림이 열려 돌고 있는가" | "직전 구간 최대 샘플값이 얼마인가"
    ///   무음 출력 앱     | ★ 1 (거짓 양성 — M-B 실측 확정) | 0.0 (정확)
    ///   배타 모드        | 잡힌다                          | ★ 0.0 (거짓 음성 — MS 문서 명시)
    ///   임계값 개념      | <b>성립하지 않는다</b>          | 성립한다
    /// </code>
    /// <b>레벨을 이 계약에 넣으면 macOS 구현체는 <c>isRunning ? 1.0f : 0.0f</c>를 지어내야 하고,</b>
    /// 그 순간 <see cref="AudioReactiveDancePolicy"/>가 <b>무엇을 재고 있는지 말할 수 없게 된다</b> —
    /// 이 저장소가 반복해 당한 <i>"실패한 측정과 성공한 측정이 똑같이 생긴"</i> 형태 그 자체다.
    /// ⇒ <b>레벨 → 불리언 변환(임계값)은 Windows 구현체가 소유한다.</b> macOS는 변환이 필요 없다.
    ///
    /// ============================================================================
    /// ★ 왜 이 파일이 <c>Platform/</c> 루트에 있는가
    /// ============================================================================
    /// <see cref="FullscreenSuspendPolicy"/> 사고 그대로다 — 계약이 <c>Platform/MacOS/</c> 안에 있으면
    /// Windows 구현이 <b>물리적으로 같은 계약을 달 수 없고</b>, 그쪽 라운드가 다른 모양을 새로 만든다.
    /// 그리고 이 개발 머신에는 Windows가 없으므로, 계약이 중립이라야 EditMode가 <b>양 플랫폼의
    /// 판정을 실제로 검증</b>할 수 있다(플랫폼 폴더 안의 규칙은 여기서 한 번도 컴파일되지 않는다).
    ///
    /// ============================================================================
    /// ★★★ <b>캡처(입력) API를 절대 쓰지 않는다</b> — 이 계약의 존재 이유의 절반이다
    /// ============================================================================
    /// 이 인터페이스의 두 구현체는 <b>오디오 샘플을 한 개도 읽지 않는다.</b> 상태/미터 <b>프로퍼티
    /// 조회</b>만 한다. 그래서:
    /// <list type="bullet">
    ///   <item><b>macOS</b> — TCC 마이크 동의창이 <b>뜨지 않는다</b>(출력 스코프
    ///     <c>...ScopeGlobal</c>의 상태 프로퍼티만 읽는다). 실측으로 확인했다(M-A/B/C/D).</item>
    ///   <item><b>Windows</b> — 백신 프로필이 「도청」으로 바뀌지 않는다. 우리 Win32 표면은 이미
    ///     창 제목 열거 + 키 상태 폴링 조합이라 휴리스틱상 애드웨어/키로거 모양이고
    ///     (<c>docs/security/ENTITLEMENT_CONTRACT.md</c> S-3), 사용자 실기는 AhnLab V3다.
    ///     여기에 루프백 캡처가 더해지면 되돌릴 수 없다.</item>
    /// </list>
    /// <b><c>Tests/EditMode/PlatformParityAuditTests</c>의 캡처 금지 니들 7종이 이 약속을 잠근다.</b>
    /// 그 감사를 "내가 하려는 일이 걸리니까" 지우는 형태로 이 저장소는 이미 한 번 당했다(§9-2-4).
    /// </summary>
    public interface ISystemAudioActivityProbe
    {
        /// <summary>진단 로그에 찍히는 구현 식별자(<c>"macOS/CoreAudio"</c> 등). 사용자 신고에서
        /// <b>어느 다리로 서 있었는지</b>를 가리기 위한 것이지 판정에 쓰이지 않는다.</summary>
        string PlatformTag { get; }

        /// <summary>
        /// 지금 시스템 기본 <b>출력</b> 장치로 소리가 나가고 있는가.
        ///
        /// <para><b>반환값이 <c>false</c>면 <paramref name="isPlaying"/>을 읽지 마라</b> —
        /// "모른다"와 "안 난다"는 다르다. 조회 실패를 <c>false</c>(=무음)로 접으면 게이트가
        /// <b>영원히 발동하지 않는 상태를 정상으로 오인</b>한다.</para>
        ///
        /// <para><b>레벨은 여기서 나오지 않는다</b>(위 I-13 문단). Windows 구현체가 자기 임계값으로
        /// 이미 불리언으로 접은 뒤 넘긴다.</para>
        /// </summary>
        /// <param name="isPlaying">재생 중이면 true. 반환값이 false일 때는 의미 없다.</param>
        /// <returns>조회에 성공했으면 true.</returns>
        bool TryReadIsAudioPlaying(out bool isPlaying);

        /// <summary>
        /// ★ 이 플랫폼의 <b>OS API가</b> 전이 푸시 알림을 제공하는가.
        ///
        /// <para><b>이 값은 「지금 우리가 푸시를 구독하고 있다」는 뜻이 아니다.</b> 구현체는 이번
        /// 라운드에 <b>양 플랫폼 모두 폴링(풀)만</b> 한다 — 이 계약 자체가 풀 API
        /// (<see cref="TryReadIsAudioPlaying"/>)이기 때문이다. 그 사실을 헷갈리면
        /// "푸시라니까 폴링을 늦춰도 되겠지"라는 판단이 조용히 틀린다.</para>
        ///
        /// <para>값의 용도는 하나다: <b>폴링 주기를 정하는 쪽이 이 플랫폼에서 푸시로 갈아탈 여지가
        /// 있는지</b>를 안다. macOS는 <c>AudioObjectAddPropertyListener</c> 실측 확인
        /// (등록 status=0, 폴링 0회로 전이 4건 수신 — M-D). Windows는 재생 상태에 대한 푸시가
        /// 확인되지 않았다(<c>IMMNotificationClient</c>는 <b>장치 변경</b> 알림이지 재생 상태가 아니다).</para>
        /// </summary>
        bool SupportsPushNotification { get; }
    }
}
